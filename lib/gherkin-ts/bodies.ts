// Playwright bodies for the step templates in templates.ts. A body is the inside of the step's
// method on the generated steps class: `this.page`, `this.request` and the helpers below, with
// the template's slots as parameters (names from paramName in compile.ts: `{a_one}` -> `one`,
// `{label_lc}` -> `label`, `{item_name}` -> `itemName`; {n} {m} {id} {status} {w} {h} {bpm} are
// numbers, the rest strings).
//
// Templates with no body here compile to a stub that marks the test fixme: they need the app's
// own data or state (seeding records, signing a role in, game and canvas state).
//
// Helpers a body may call (compile.ts emits only the ones used):
//   this.urlFor(page)        route of a named page, "/" + kebab case
//   this.apiPath(noun)       "/api/<plural noun>"
//   this.exactly(s)          case-insensitive whole-string RegExp (Yumon writes lowercase)
//   this.containing(s)       case-insensitive substring RegExp
//   this.rows()              list items, tree items and table body rows
//   this.item(name)          first row with that text
//   this.key(k)              Playwright key name from a lowercase one ("control+s" -> "Control+s")
//   this.res(), this.json(), this.items()   last API response, its body, its list
//   this.data, this.headers  body and headers of the next API request
//   this.downloads           suggested file names of every download so far

