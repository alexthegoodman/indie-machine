// Writes lib/analytics/world-map.ts: Natural Earth 1:110m country outlines (world-atlas, public
// domain data) pre-projected to SVG paths in Equal Earth, keyed by ISO alpha-2 (what Vercel's
// x-vercel-ip-country header carries). The dashboard then needs no map library or tile server.
//   node scripts/build-world-map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoEqualEarth, geoPath } from "d3-geo";
import countries from "i18n-iso-countries";

const require = createRequire(import.meta.url);
const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
const en = JSON.parse(readFileSync(require.resolve("i18n-iso-countries/langs/en.json"), "utf8"));
countries.registerLocale(en);

const W = 1000;
const all = feature(topo, topo.objects.countries).features.filter((f) => f.id !== "010"); // no Antarctica
const projection = geoEqualEarth().fitWidth(W, { type: "FeatureCollection", features: all });
const path = geoPath(projection).digits(1);
const [[, y0], [, y1]] = path.bounds({ type: "FeatureCollection", features: all });
const H = Math.ceil(y1 - y0 + 2);
projection.translate([projection.translate()[0], projection.translate()[1] - y0 + 1]);

// Shapes without an ISO numeric id in world-atlas: Kosovo (Vercel sends XK), and two drawn
// apart from the country Vercel reports them as.
const BY_NAME = { Kosovo: "XK", "N. Cyprus": "CY", Somaliland: "SO" };

const out = [];
for (const f of all) {
  const a2 = f.id ? countries.numericToAlpha2(f.id) : BY_NAME[f.properties.name];
  const d = path(f);
  if (!d) continue;
  out.push({ a2: a2 ?? null, name: f.properties.name, d });
}

const [tx, ty] = projection.translate();
const src = `// Generated by scripts/build-world-map.mjs from world-atlas@2 countries-110m (Natural Earth,
// public domain). Equal Earth, fit to ${W} wide. Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
/** Equal Earth scale and translate used for the paths, so points can be projected to match. */
export const MAP_K = ${projection.scale()};
export const MAP_T: [number, number] = [${tx}, ${ty}];
export const COUNTRIES: { a2: string | null; name: string; d: string }[] = ${JSON.stringify(out)};
`;
writeFileSync(new URL("../lib/analytics/world-map.ts", import.meta.url), src);

// Self-check for lib/analytics/geo.ts's point projection against d3.
const { project } = await import("../lib/analytics/geo.ts");
let worst = 0;
for (const p of [[0, 0], [-122.4, 37.8], [139.7, 35.7], [-58.4, -34.6], [151.2, -33.9], [37.6, 55.8]]) {
  const [ax, ay] = projection(p);
  const [bx, by] = project(p[1], p[0]);
  worst = Math.max(worst, Math.hypot(ax - bx, ay - by));
}
console.log(`${out.length} shapes, ${out.filter((c) => !c.a2).length} without a code, ${(src.length / 1024).toFixed(0)} KB, ${W}x${H}, point error vs d3 ${worst.toExponential(1)} px`);
