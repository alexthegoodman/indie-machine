// Splits lib/gherkin-app/library.ts into its top-level declarations for the Gherkin app compiler:
// each one's TypeScript (without `export`), its JavaScript (types stripped by TypeScript's
// transpileModule) and the other declarations it uses. An app copies in only what it calls,
// plus their dependencies, in file order. Writes lib/gherkin-app/library.gen.ts.
//
//   node scripts/build-gherkin-library.mjs
import fs from "node:fs";
import path from "node:path";
import ts from "typescript";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "lib", "gherkin-app", "library.ts");
const OUT = path.join(ROOT, "lib", "gherkin-app", "library.gen.ts");

const text = fs.readFileSync(SRC, "utf8");
const file = ts.createSourceFile(SRC, text, ts.ScriptTarget.ES2022, true);

const decls = [];
for (const st of file.statements) {
  let name;
  if (ts.isFunctionDeclaration(st) || ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st)) name = st.name?.text;
  else if (ts.isVariableStatement(st)) {
    const names = st.declarationList.declarations.map((d) => d.name.getText(file));
    if (names.length !== 1) throw new Error(`one name per const please: ${names}`);
    name = names[0];
  } else throw new Error(`unsupported top-level statement: ${st.getText(file).slice(0, 60)}`);
  // From the JSDoc (if any) to the end; line comments above it are section notes and stay out.
  const code = text.slice(st.getStart(file, true), st.getEnd()).replace(/^((?:\/\*\*[\s\S]*?\*\/\s*)?)export /, "$1").trim();
  const type = ts.isTypeAliasDeclaration(st) || ts.isInterfaceDeclaration(st);
  decls.push({ name, node: st, ts: code, type });
}
const names = new Set(decls.map((d) => d.name));
for (const d of decls) {
  const used = new Set();
  const walk = (n) => {
    const p = n.parent;
    // Property names ({ value: ... }, obj.value) are not uses of a declaration called `value`.
    const prop = p && ((ts.isPropertyAccessExpression(p) && p.name === n) || ((ts.isPropertyAssignment(p) || ts.isPropertySignature(p)) && p.name === n));
    if (ts.isIdentifier(n) && !prop && names.has(n.text) && n.text !== d.name) used.add(n.text);
    ts.forEachChild(n, walk);
  };
  ts.forEachChild(d.node, walk);
  d.deps = [...used];
  d.js = d.type
    ? ""
    : ts
        .transpileModule(d.ts, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext, removeComments: false } })
        .outputText.replace(/^export \{\};\s*$/m, "")
        .trim();
}

const out = [
  "// Generated by scripts/build-gherkin-library.mjs from library.ts. Do not edit: rerun the script.",
  "",
  "export type LibraryEntry = { ts: string; js: string; deps: string[] };",
  "",
  "/** Top-level declarations of library.ts in file order. */",
  "export const LIBRARY: Record<string, LibraryEntry> = {",
  ...decls.map((d) => `  ${JSON.stringify(d.name)}: { ts: ${JSON.stringify(d.ts)}, js: ${JSON.stringify(d.js)}, deps: ${JSON.stringify(d.deps)} },`),
  "};",
  "",
];
fs.writeFileSync(OUT, out.join("\n"));
console.log(`${decls.length} declarations -> ${path.relative(ROOT, OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(1)} KB)`);
