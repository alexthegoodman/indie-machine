// Copies the step templates of yumon-pet's procedural Gherkin generator (scripts/gherkin/generate.mjs,
// creative.mjs, games.mjs) into lib/gherkin-ts/templates.ts, where the Gherkin -> TypeScript compiler
// on /free-ai/gherkin matches Yumon's lines against them. Only step lines (g./w./t_. keys) are kept:
// headers, user stories and scenario titles are structure, not steps.
//
//   node scripts/build-gherkin-templates.mjs [path/to/yumon-pet/scripts/gherkin]
//
// generate.mjs runs a whole generation when imported, so its STEPS literal is read as text.
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.resolve(process.argv[2] ?? path.join(ROOT, "..", "yumon-pet", "scripts", "gherkin"));
const OUT = path.join(ROOT, "lib", "gherkin-ts", "templates.ts");

const gen = fs.readFileSync(path.join(SRC, "generate.mjs"), "utf8");
const literal = (name, close) => {
  const start = gen.indexOf(`const ${name} = `);
  if (start < 0) throw new Error(`${name} not found in generate.mjs`);
  const end = gen.indexOf(close, start);
  return gen.slice(start + `const ${name} = `.length, end + close.length - 1);
};
const base = new Function(`return ${literal("STEPS", "\n};")}`)();
const singular = new Function(`return ${literal("SINGULAR", "]];")}`)();
const creative = await import(pathToFileURL(path.join(SRC, "creative.mjs")).href);
const games = await import(pathToFileURL(path.join(SRC, "games.mjs")).href);

const all = { ...base };
for (const mod of [creative, games]) for (const [k, v] of Object.entries(mod.STEPS)) {
  if (k in all) throw new Error(`duplicate template ${k}`);
  all[k] = v;
}
const steps = Object.entries(all).filter(([k]) => /^(g|w|t_)\./.test(k));

const out = [
  "// Generated by scripts/build-gherkin-templates.mjs from yumon-pet scripts/gherkin (generate.mjs,",
  "// creative.mjs, games.mjs). Do not edit: rerun the script when the generator changes.",
  `// ${Object.keys(all).length} templates in the generator, ${steps.length} of them step lines.`,
  "",
  "/** Step templates: key (g. context, w. action, t_. outcome) -> line without its keyword. */",
  "export const STEP_TEMPLATES: Record<string, string> = {",
  ...steps.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`),
  "};",
  "",
  "/** The generator rewrites these plural phrases to singular when {n} is 1. */",
  "export const SINGULAR: [string, string][] = [",
  ...singular.map(([a, b]) => `  [${JSON.stringify(a)}, ${JSON.stringify(b)}],`),
  "];",
  "",
];
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out.join("\n"));
console.log(`${steps.length} step templates (of ${Object.keys(all).length}) -> ${path.relative(ROOT, OUT)}`);
